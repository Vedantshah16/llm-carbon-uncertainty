"""Write results/RESULTS.md: every number quoted in the paper, read from results/*.csv.
Usage: python src/report.py
"""
import json
from pathlib import Path
import pandas as pd
from config import RUNS, PRIORS, META_CAMPUS_ZONES, MC_SAMPLES, SEEDS, SOBOL_N

RES = Path(__file__).resolve().parents[1] / "results"
mc = pd.read_csv(RES / "mc_summary.csv").set_index("run")
sb = pd.read_csv(RES / "sobol_summary.csv")
sw = pd.read_csv(RES / "zone_sweep.csv")
hv = pd.read_csv(RES / "hourly_vs_annual.csv")
cv = pd.read_csv(RES / "mc_convergence.csv")
ex = json.loads((RES / "extras.json").read_text(encoding="utf-8"))

L = ["# Results summary (auto-generated by src/report.py — do not edit by hand)\n",
     f"Monte Carlo: {MC_SAMPLES:,} samples x seeds {SEEDS}; values are means across seeds, "
     "± = SD across seeds. Sobol: Saltelli/Sobol' design, "
     f"N = {SOBOL_N:,} base samples, first- and total-order indices, seeds {SEEDS}.\n"]

L.append("## Table I — Disclosed inputs per run\n")
L.append("| Run | Accel. | TDP (W) | GPU-h | Region | Window (UTC) | GPUs | PUE prior | Reported op. tCO2e |")
L.append("|---|---|---|---|---|---|---|---|---|")
for r in RUNS:
    reg = r.zones[0] if len(r.zones) == 1 else f"{len(set(r.zones))} zones ({len(r.zones)} sites)"
    gh = f"{r.gpu_hours:,.0f}" if r.gpu_hours else f"measured {r.measured_it_kwh:,.0f} kWh IT"
    ng = r.n_gpu[0] if r.n_gpu[0] == r.n_gpu[1] else f"{r.n_gpu[0]:,}–{r.n_gpu[1]:,}"
    L.append(f"| {r.label} | {r.accel} | {r.tdp_kw*1000:.0f} | {gh} | {reg} | "
             f"{r.window[0][:10]} → {r.window[1][:10]} | {ng} | {r.pue[0]}–{r.pue[1]} | {r.reported_op_t:g} |")

L.append("\n## Table II — Totals with uncertainty vs standard practice\n")
L.append("| Run | Median total (t) | 90 % interval (t) | Baseline (t) | Reported op. (t) | Reported in op. 90 %? | P(op > reported) | Embodied share median [90 %] | Hourly-vs-annual CI error median [90 %] |")
L.append("|---|---|---|---|---|---|---|---|---|")
for r in RUNS:
    m = mc.loc[r.key]
    L.append(f"| {r.label} | {m.total_q50:,.1f} ± {m.total_q50_sd:.1f} | [{m.total_q05:,.1f}, {m.total_q95:,.1f}] | "
             f"{m.baseline_t:,.1f} | {r.reported_op_t:g}" +
             (f" (total {r.reported_total_t:g})" if r.reported_total_t else "") +
             f" | {'yes' if m.reported_op_in_op_90 else 'NO'} | {m.p_op_gt_reported_op:.2f} | "
             f"{100*m.emb_share_q50:.1f} % [{100*m.emb_share_q05:.1f}, {100*m.emb_share_q95:.1f}] | "
             f"{100*m.hourly_err_q50:+.1f} % [{100*m.hourly_err_q05:+.1f}, {100*m.hourly_err_q95:+.1f}] |")
L.append("\nOperational-only 90 % intervals (t): " + "; ".join(
    f"{r.label} [{mc.loc[r.key].op_q05:,.1f}, {mc.loc[r.key].op_q95:,.1f}]" for r in RUNS))
L.append("Median total / baseline: " + "; ".join(
    f"{r.label} {mc.loc[r.key].median_over_baseline:.2f}x" for r in RUNS))

L.append("\n## Sobol total-order indices (mean across seeds; S1 in brackets)\n")
for r in RUNS:
    s = sb[sb.run == r.key].sort_values("ST", ascending=False)
    L.append(f"- **{r.label}**: " + ", ".join(
        f"{i} {st:.2f} ({s1:.2f}; ±{c:.2f})" for i, st, s1, c in
        zip(s.input, s.ST, s.S1, s.ST_conf)))

L.append("\n## Zone sweep (Llama 2 70B job placed in each grid, 2023)\n")
L.append("| Zone | Annual CI 2023 (g/kWh) | Embodied share median [90 %] | ST embodied/GPU | ST power |")
L.append("|---|---|---|---|---|")
for _, z in sw.iterrows():
    L.append(f"| {z.zone} | {z.ci_annual_2023_mean:.1f} | {100*z.emb_share_q50_mean:.1f} % "
             f"[{100*z.emb_share_q05_mean:.1f}, {100*z.emb_share_q95_mean:.1f}] | "
             f"{z.ST_c_emb_mean:.2f} | {z.ST_power_mean:.2f} |")

L.append("\n## Annual-average vs hourly CI (15 grids, 2021–2024)\n")
piv = hv.pivot(index="hours", columns="zone", values="abs_err_q50_mean")
L.append("| Duration (h) | Median over grids of median abs. error | Min grid | Max grid |")
L.append("|---|---|---|---|")
for h, row in piv.iterrows():
    L.append(f"| {h} | {100*row.median():.1f} % | {100*row.min():.1f} % ({row.idxmin()}) | "
             f"{100*row.max():.1f} % ({row.idxmax()}) |")

L.append("\n## Checks and extras\n")
L.append(f"- BLOOM: FR mean CI over actual training window = {ex['bloom_ci_window_g_per_kwh']:.1f} g/kWh; "
         f"FR 2022 annual mean = {ex['bloom_ci_annual_2022']:.1f}; value used in paper = {ex['bloom_ci_used_in_paper']}; "
         f"FR 2022 hourly range = {ex['fr2022_hourly_min_max'][0]:.1f}–{ex['fr2022_hourly_min_max'][1]:.1f} g/kWh.")
lo, hi = ex["prior_rho_plus_eta_q05_q95"]
L.append(f"- Power-prior validation: BLOOM measured dynamic/(GPU-h x TDP) = {ex['bloom_measured_dynamic_over_tdp']:.2f}; "
         f"(dynamic + idle)/(GPU-h x TDP) = {ex['bloom_measured_dynamic_plus_idle_over_tdp']:.2f}; "
         f"prior (rho+eta) 5–95 % = [{lo:.2f}, {hi:.2f}].")
L.append(f"- OLMo-7B on LUMI reported 0 t (market-based). Location-based with FI 2023 annual CI "
         f"({ex['olmo_lumi_fi2023_annual_ci']:.1f} g/kWh) x 135 MWh x PUE 1.1 = {ex['olmo_lumi_location_based_t']:.2f} t.")
L.append(f"- Meta-site equal-weight 2022 annual CI = {ex['meta_sites_equal_weight_ci_2022']:.1f} g/kWh (LLaMA paper used 385).")
L.append(f"- BLOOM embodied median = {mc.loc['bloom'].emb_q50:.1f} t [90 %: {mc.loc['bloom'].emb_q05:.1f}, {mc.loc['bloom'].emb_q95:.1f}]; "
         f"Llama 3.1 405B operational median = {mc.loc['llama31_405b'].op_q50:,.1f} t.")
for zn in ("FR", "FI", "SE", "PL"):
    v = piv.loc[2160, zn]
    L.append(f"- Annual-average median abs. error at 2160 h (90 d), {zn}: {100*v:.1f} %")
L.append(f"- Eq. (5) with BLOOM's own embodied assumptions gives {ex['check_eq5_bloom_gpu_embodied_t']:.2f} t "
         "(paper: 3.64 t GPU embodied) — model reproduces the published figure.")
L.append(f"- Reported figures from their own stated inputs: LLaMA-65B {ex['check_llama65b_t']:.1f} t (paper 173); "
         f"OLMo-7B A100 104 MWh x 1.1 x 0.610 = {ex['check_olmo_a100_t']:.1f} t (paper 70).")
L.append(f"- CI implied by Meta's reported figures (power column already PUE-adjusted): Llama 2 70B "
         f"{ex['implied_ci_llama2_70b']:.1f} g/kWh; Llama 3.1 405B {ex['implied_ci_llama31_405b']:.1f} g/kWh.")
L.append("- Life-cycle / direct CI ratio for each run's zones (scope sensitivity, not in main model): " +
         ", ".join(f"{k} {v:.2f}" for k, v in ex["lca_over_direct_ci_ratio"].items()))
L.append("- Hours filled by interpolation per zone: " +
         ", ".join(f"{k} {v}" for k, v in ex["interpolated_hours"].items() if v))
c = cv.groupby("n")[["q50", "q95"]].agg(["mean", "std"])
L.append(f"- MC convergence ({cv.run.iloc[0]}): " + "; ".join(
    f"n={n:,}: median {row[('q50','mean')]:.1f}±{row[('q50','std')]:.1f}, "
    f"q95 {row[('q95','mean')]:.1f}±{row[('q95','std')]:.1f}" for n, row in c.iterrows()))

L.append("\n## Priors used (assumptions)\n")
for k, v in PRIORS.items():
    L.append(f"- {k}: {v}")
L.append("- Meta campus → zone map: " + ", ".join(f"{a} → {b}" for a, b in META_CAMPUS_ZONES.items()))
(RES / "RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("wrote results/RESULTS.md")
